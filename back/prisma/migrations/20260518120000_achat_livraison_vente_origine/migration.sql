SELECT COUNT(*) INTO @fk FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
  WHERE CONSTRAINT_SCHEMA = DATABASE() AND TABLE_NAME = 'Vente' AND CONSTRAINT_NAME = 'Vente_venteOrigineId_fkey';
SET @qf = IF(@fk = 0,
  'ALTER TABLE `Vente` ADD CONSTRAINT `Vente_venteOrigineId_fkey` FOREIGN KEY (`venteOrigineId`) REFERENCES `Vente`(`id`) ON DELETE SET NULL ON UPDATE CASCADE',
  'SELECT 1');
PREPARE sf FROM @qf; EXECUTE sf; DEALLOCATE PREPARE sf;
