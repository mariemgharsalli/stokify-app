-- Sync MySQL avec schema Prisma (achats/ventes, avoirs) — idempotent.

-- Achat: dates livraison + retard
SELECT COUNT(*) INTO @c1 FROM INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'Achat' AND COLUMN_NAME = 'dateLivraisonPrevue';
SET @q1 = IF(@c1 = 0, 'ALTER TABLE `Achat` ADD COLUMN `dateLivraisonPrevue` DATETIME(3) NULL', 'SELECT 1');
PREPARE s1 FROM @q1; EXECUTE s1; DEALLOCATE PREPARE s1;

